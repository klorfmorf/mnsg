// Declares the ROM and RAM symbols the linker script defines for splat segment `name`.
#define DECLARE_SEGMENT(name)                \
    extern unsigned char name##_ROM_START[]; \
    extern unsigned char name##_ROM_END[];   \
    extern unsigned char name##_VRAM[];      \
    extern unsigned char name##_VRAM_END[]

// Declares the RAM symbols the linker script defines for splat segment `name` that only has bss.
#define DECLARE_BSS_SEGMENT(name)           \
    extern unsigned char name##_bss_VRAM[]; \
    extern unsigned char name##_VRAM_END[]

// ROM start and end offsets of splat segment `name`, as declared by DECLARE_SEGMENT.
#define FILE_ROM_START(name) ((unsigned int) name##_ROM_START)
#define FILE_ROM_END(name)   ((unsigned int) name##_ROM_END)

// RAM start and end addresses of splat segment `name`, as declared by DECLARE_SEGMENT.
#define FILE_RAM_START(name) ((unsigned int) name##_VRAM)
#define FILE_RAM_END(name)   ((unsigned int) name##_VRAM_END)

// RAM start and end addresses of splat segment `name` that only has bss and is not in the ROM, as
// declared by DECLARE_BSS_SEGMENT.
#define FILE_BSS_START(name) ((unsigned int) name##_bss_VRAM)
#define FILE_BSS_END(name)   ((unsigned int) name##_VRAM_END)

